# %% [markdown]
# # Сегментация по подсказке. SAM 2
#
# YOLO сама находит все объекты известных ей классов. SAM 2 (Segment Anything Model 2) работает иначе:
# он не распознаёт классы, а выделяет тот объект, который ему указали подсказкой (prompt).
#
# Подсказки бывают двух видов:
# - точка (пиксель объекта) — «вот здесь объект, выдели его целиком»;
# - рамка (bounding box) — «объект примерно здесь».
#
# Результат уточняют добавлением новых подсказок: положительная точка (`labels=1`) говорит
# «объект здесь», отрицательная (`labels=0`) — «а здесь не объект».
#
# Документация: https://docs.ultralytics.com/models/sam-2/


# %% Cell 10
from pathlib import Path

from PIL import Image, ImageDraw
from ultralytics import SAM

# %% [markdown]
# ### Загрузка предварительно обученной модели


# %% Cell 20
MODELS_DIR = Path("models/")
IMAGES_DIR = Path("../images/")   # общая папка с картинками для всех примеров
MODEL = "sam2.1_t.pt"   # tiny — самый маленький вариант (около 80 Мб), есть ещё s / b / l
model = SAM(MODELS_DIR / MODEL)
# если файла с весами нет, он скачается в эту папку

# %%
# изображение для проверки
image_path = IMAGES_DIR / "peoples_and_dog.jpg"
img = Image.open(image_path)
print(f"resolution: {img.width}x{img.height}")
img

# %% [markdown]
# ### Как задать координаты подсказки
#
# Подсказка — это координаты в пикселях: `x` растёт вправо, `y` — вниз, начало координат (0, 0) —
# левый верхний угол изображения. В API нет интерактивного клика мышью: координаты передаются
# числами. Чтобы их удобно было снимать, нарисуем поверх картинки сетку с шагом 100 пикселей.

# %%
# картинка с сеткой: подписи — координаты в пикселях
image = Image.open(image_path).convert("RGB")
draw = ImageDraw.Draw(image)

step = 100
for x in range(0, image.width, step):
    draw.line([(x, 0), (x, image.height)], fill=(255, 255, 0))
    draw.text((x + 3, 3), str(x), fill="yellow")
for y in range(0, image.height, step):
    draw.line([(0, y), (image.width, y)], fill=(255, 255, 0))
    draw.text((3, y + 3), str(y), fill="yellow")

image

# %% [markdown]
# ### Подсказка точкой
#
# Указываем один пиксель внутри объекта — модель выделяет весь объект.
# Координаты ниже — пример; подберите свои по сетке из предыдущей клетки.

# %%
point = [480, 300]   # [x, y] — пиксель внутри объекта  ( женщина )
# point = [350, 200]   # [x, y] — пиксель внутри объекта  ( мужчина )
# point = [450, 550]   # [x, y] — пиксель внутри объекта  ( дорога )
# point = [700, 400]   # [x, y] — пиксель внутри объекта  ( дорога )
# point = [930, 330]   # [x, y] — пиксель внутри объекта  ( вода )

result = model(image_path, points=[point], labels=[1])   # 1 — положительная точка

Image.fromarray(result[0].plot()[:, :, ::-1])   # BGR -> RGB

# %%
# маска выделенного объекта — та же структура Results, что и у YOLO
mask = result[0].masks.data[0].cpu().numpy()   # [H, W], 1 — пиксель принадлежит объекту
print(f"доля пикселей изображения, занятая объектом: {mask.mean():.3f}")

# %% [markdown]
# ### Уточнение маски несколькими точками
#
# Если модель захватила лишнее или пропустила часть объекта, добавляем точки:
# положительные (`1`) — «объект здесь», отрицательные (`0`) — «а здесь не объект».

# %%
points = [[480, 300], [700, 500]]   # первая точка — объект, вторая — фон
labels = [1, 0]

result = model(image_path, points=points, labels=labels)

Image.fromarray(result[0].plot()[:, :, ::-1])

# %% [markdown]
# ### Подсказка рамкой
#
# Рамка задаётся двумя углами: `[x1, y1, x2, y2]` — левый верхний и правый нижний.
# Рамка обычно надёжнее одной точки: модель сразу понимает и положение, и примерный размер объекта.

# %%
bbox = [600, 350, 850, 600]   # [x1, y1, x2, y2]

result = model(image_path, bboxes=[bbox])

Image.fromarray(result[0].plot()[:, :, ::-1])

# %% [markdown]
# ### Работа с масками
#
# Структура результата та же, что в `yolo_segmentation.py`: `masks.data` — бинарные маски,
# `masks.xy` — контуры объектов в координатах изображения. Отличие от YOLO: SAM 2 не возвращает
# классы и уверенность — он выделяет именно то, что показано подсказкой, даже если не знает,
# как этот объект называется.

# %%
# своя отрисовка: полупрозрачная маска поверх картинки
image = Image.open(image_path).convert("RGB")
draw = ImageDraw.Draw(image, "RGBA")

for polygon in result[0].masks.xy:
    if len(polygon) < 3:   # контур из менее чем 3 точек не нарисовать
        continue
    draw.polygon([tuple(p) for p in polygon], fill=(255, 0, 0, 100), outline=(255, 0, 0, 255), width=3)

image

